//=============================================================================
// conv_ctrl_fsm.v - Main control FSM for single-PE 3x3 convolution
//--------------------------------------------------------------------------
// State machine: IDLE -> CALC -> (done pulse) -> IDLE
//
// Pipeline/alignment model:
//   The top level delays a_en, wgt_idx and pad_valid by exactly one cycle to
//   form data_vld, tap_d1, pad_d1 -- all aligned with the BRAM data currently
//   on the wire (the data issued on the previous a_en edge). The IFM/WGT data
//   is consumed directly by the PE from the BRAM outputs.
//
//   Because the PE is registered, its control must be *combinational* on the
//   aligned signals so the PE samples (data, tap, control) on the same edge:
//       acc_clr = data_vld && tap_d1 == 0        (load first product)
//       acc_en  = data_vld && 1 <= tap_d1 <= 7   (accumulate)
//   The OFM write is generated from tap_d1 == TAPS-1 and REGISTERED (the
//   settled result is valid one cycle later), then the write fires.
//
// done is generated by the top level (last-pixel write); this FSM returns to
// IDLE on the finish pulse.
//
// Design rules (per AGENTS.md): pure Verilog-2001; non-blocking sequential;
// explicit active-low reset; single clock domain.
//=============================================================================

module conv_ctrl_fsm #(
    parameter IMG_H  = 16,   // output height
    parameter IMG_W  = 16,   // output width
    parameter K_SIZE = 3,
    parameter TAPS   = K_SIZE * K_SIZE   // 9
)(
    input  wire        clk,       // clock
    input  wire        rst_n,     // active-low reset
    // control
    input  wire        start,     // start a convolution (pulse)
    output reg         busy,      // 1 while computing
    // driving addr_gen
    output reg         addr_en,   // advance window one tap
    // data indicator + tap index (from top level, aligned with the data)
    input  wire        data_vld,  // high when a tap's data is stable
    input  wire [3:0]  tap_d1,    // tap index (0..8) of the current data
    // finish pulse from top level (last pixel written)
    input  wire        finish,
    // driving PE
    output wire        acc_clr,   // combinational: load first product of a pixel
    output wire        acc_en,    // combinational: accumulate (taps 1..7)
    output reg         ofm_wr_en  // registered: write result to OFM (+1 cycle)
);

    //-------------------------------------------------------------------------
    // State encoding.
    //-------------------------------------------------------------------------
    localparam IDLE = 2'b00;
    localparam CALC = 2'b01;

    reg [1:0] state;
    reg [1:0] state_nxt;

    //-------------------------------------------------------------------------
    // Next-state logic (combinational, blocking).
    //-------------------------------------------------------------------------
    always @* begin
        state_nxt = state;
        case (state)
            IDLE: begin
                if (start) state_nxt = CALC;
            end
            CALC: begin
                if (finish) state_nxt = IDLE;
            end
            default: state_nxt = IDLE;
        endcase
    end

    //-------------------------------------------------------------------------
    // Sequential state update.
    //-------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            state <= IDLE;
        end else begin
            state <= state_nxt;
        end
    end

    //-------------------------------------------------------------------------
    // addr_en (combinational): advance the window every cycle during CALC.
    //-------------------------------------------------------------------------
    always @* begin
        addr_en = 1'b0;
        if (state == CALC) begin
            addr_en = 1'b1;
        end
    end

    //-------------------------------------------------------------------------
    // PE controls: combinational so the PE samples them with the data.
    // tap0 is loaded via acc_clr; taps 1..8 accumulate via acc_en (all 9
    // kernel taps are therefore covered).
    //-------------------------------------------------------------------------
    assign acc_clr = data_vld && (tap_d1 == 4'd0);
    assign acc_en  = data_vld && (tap_d1 >= 4'd1) && (tap_d1 <= TAPS-1);

    //-------------------------------------------------------------------------
    // OFM write enable: registered from tap_d1 == TAPS-1 (settled result).
    //-------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            ofm_wr_en <= 1'b0;
        end else begin
            ofm_wr_en <= data_vld && (tap_d1 == TAPS-1);
        end
    end

    //-------------------------------------------------------------------------
    // busy (combinational).
    //-------------------------------------------------------------------------
    always @* begin
        busy = (state == CALC);
    end

endmodule
